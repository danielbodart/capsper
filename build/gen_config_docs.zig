//! Harvesting the settings' descriptions out of `src/shared/config.zig`.
//!
//! The prose describing each setting already exists, as the doc comment beside
//! it, and that is where it should stay: next to the default it describes,
//! where it is read and edited by anyone changing the field. What it cannot do
//! there is reach the program. `@typeInfo` gives a field's name and type and
//! says nothing about its doc comment, so a running capsper has no way to tell
//! you what `audio.gain` means.
//!
//! So this reads the source. `std.zig.Ast` is the same parser the compiler
//! uses, which is why this is a parse rather than a regular expression over
//! the text -- a doc comment is found by position in the token stream, not by
//! guessing where one might be.
//!
//! It runs at build time and not at comptime because parsing needs an
//! allocator and comptime has none.
//!
//! The output is deliberately dumb: a flat list of container name, field name
//! and text, with no attempt to resolve which type a field holds. Resolving
//! types from an AST means reimplementing name resolution, and there is no
//! need -- `src/shared/config_docs.zig` walks the real types with `@typeInfo`,
//! where the answer is already known, and looks each field up here by name.
//!
//! Note that the ZON file these describe could not carry this itself. ZON
//! accepts `//` comments but Zig's tokenizer discards them, so a comment in a
//! parsed ZON file leaves nothing behind to read.

const std = @import("std");

pub fn main() !void {
    var arena_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    const args = try std.process.argsAlloc(arena);
    if (args.len != 3) {
        std.debug.print("usage: gen-config-docs <config.zig> <out.zig>\n", .{});
        std.process.exit(1);
    }

    const source = try std.fs.cwd().readFileAllocOptions(
        arena,
        args[1],
        4 << 20,
        null,
        .of(u8),
        0,
    );

    var ast = try std.zig.Ast.parse(arena, source, .zig);
    defer ast.deinit(arena);

    if (ast.errors.len > 0) {
        std.debug.print("{s}: does not parse\n", .{args[1]});
        std.process.exit(1);
    }

    var out: std.Io.Writer.Allocating = .init(arena);
    try out.writer.writeAll(
        \\//! Generated by build/gen_config_docs.zig. Do not edit.
        \\//!
        \\//! The doc comment beside each field in src/shared/config.zig, made
        \\//! readable by the program. See src/shared/config_docs.zig.
        \\
        \\pub const Field = struct {
        \\    /// The container the field is declared in, as written: "Audio".
        \\    container: []const u8,
        \\    name: []const u8,
        \\    /// The doc comment, its `///` markers and indentation removed and
        \\    /// its lines joined with spaces. Empty when the field has none.
        \\    doc: []const u8,
        \\};
        \\
        \\pub const fields = [_]Field{
        \\
    );

    var count: usize = 0;
    for (0..ast.nodes.len) |i| {
        const node: std.zig.Ast.Node.Index = @enumFromInt(i);
        const field = ast.fullContainerField(node) orelse continue;

        const container = containerOf(ast, node) orelse continue;
        const name = ast.tokenSlice(field.ast.main_token);
        const doc = try docComment(arena, ast, field.firstToken());

        try out.writer.print("    .{{ .container = \"{f}\", .name = \"{f}\", .doc = \"{f}\" }},\n", .{
            std.zig.fmtString(container),
            std.zig.fmtString(name),
            std.zig.fmtString(doc),
        });
        count += 1;
    }

    try out.writer.writeAll("};\n");

    if (count == 0) {
        std.debug.print("{s}: found no fields, which cannot be right\n", .{args[1]});
        std.process.exit(1);
    }

    try std.fs.cwd().writeFile(.{ .sub_path = args[2], .data = out.written() });
}

/// The name of the `const X = struct { ... }` a field is declared inside.
///
/// Found by walking back through the tokens before the field for the `struct`
/// keyword that opens its container, then back again for the identifier that
/// names it. Cheaper than tracking containers through a recursive descent of
/// the tree, and the settings types are all plain `pub const X = struct`
/// declarations at the top level of one file.
///
/// Null for a field in an anonymous or nested-inline struct, which is not a
/// shape the settings use and which this has no name to report anyway.
fn containerOf(ast: std.zig.Ast, node: std.zig.Ast.Node.Index) ?[]const u8 {
    const tags = ast.tokens.items(.tag);
    const first = ast.firstToken(node);

    // Walk back to the `{` that opens this field's container, skipping any
    // balanced braces belonging to fields declared before it.
    var tok = first;
    var depth: usize = 0;
    while (tok > 0) {
        tok -= 1;
        switch (tags[tok]) {
            .r_brace => depth += 1,
            .l_brace => {
                if (depth == 0) break;
                depth -= 1;
            },
            else => {},
        }
    } else return null;

    // `... = struct {` or `... = enum(u8) {`, so the keyword is a short way
    // back from the brace but not always immediately before it.
    var kw = tok;
    const kw_floor = if (tok > 8) tok - 8 else 0;
    while (kw > kw_floor) {
        kw -= 1;
        if (tags[kw] == .keyword_struct or tags[kw] == .keyword_enum or tags[kw] == .keyword_union) break;
    } else return null;

    // `pub const Audio = struct`, so the name is two tokens before it.
    if (kw < 2) return null;
    if (tags[kw - 1] != .equal) return null;
    if (tags[kw - 2] != .identifier) return null;
    return ast.tokenSlice(kw - 2);
}

/// The doc comment immediately above a token, as one line.
///
/// Joined with spaces rather than kept as lines because every consumer wraps
/// it to its own width: the usage text to a terminal, the annotated config to
/// the comment column. Paragraph breaks, written as a `///` line on its own,
/// survive as a double space so a consumer that cares can still find them.
fn docComment(arena: std.mem.Allocator, ast: std.zig.Ast, token: u32) ![]const u8 {
    const tags = ast.tokens.items(.tag);

    var first = token;
    while (first > 0 and tags[first - 1] == .doc_comment) first -= 1;
    if (first == token) return "";

    var text: std.Io.Writer.Allocating = .init(arena);
    var tok = first;
    while (tok < token) : (tok += 1) {
        const line = std.mem.trim(u8, ast.tokenSlice(tok)[3..], " \t\r\n");
        if (tok > first) try text.writer.writeByte(' ');
        try text.writer.writeAll(line);
    }
    return text.written();
}
